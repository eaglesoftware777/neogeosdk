"""The match ground: one painted panorama seen from a camera on the halfway line.

The pitch is a true perspective trapezoid: a world point (x, y) lands at picture

    px = PCX + (x - HALF_LEN) * s,  py = PY0 + DEPTH * (s - S_FAR) / (S_NEAR - S_FAR)

where s = S_NEAR * D / (D + distance from the near touchline). The row is a straight
function of the scale, which is what keeps straight lines straight: every touchline,
box and mowing stripe. Panning over the picture is a camera turning on the spot, so the
one painting scrolls with no raster tricks. The match draws through the same
function (the tables in cx_proj.h), so a man, the ball and the markings can
never disagree about where the penalty spot is.
"""
import zlib
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

LEN, WID, HALF_LEN = 1536, 704, 768
PIC_W, PIC_H = 1824, 560
PCX = PIC_W // 2
PY0, DEPTH = 164, 296
S_FAR, S_NEAR = 0.80, 1.10
EYE = WID * S_FAR / (S_NEAR - S_FAR)    # the camera's distance behind the near touchline, in units
Z_SCALE = 1.7                       # height above the grass, in pixels per unit, at s = 1
STANDS_H = 160                      # the picture above this row is the stadium's; below, the pitch all grounds share
POST, BAR, BOX_D, BOX_W, SIX_D, SIX_W = 88, 40, 240, 300, 84, 150
Y_LO, Y_HI, Y_STEP = -64, 768, 1    # the range the tables cover, one entry a unit: a lookup, not a sum


def s_of(t):
    return S_NEAR * EYE / (EYE + (1.0 - t) * WID)


def py_of(t):
    return PY0 + DEPTH * (s_of(t) - S_FAR) / (S_NEAR - S_FAR)


def project(x, y):
    t = y / WID
    return PCX + (x - HALF_LEN) * s_of(t), py_of(t)


def inverse_t(py):
    """t for picture rows: the scale from the row, the depth from the scale."""
    s = S_FAR + (py - PY0) / DEPTH * (S_NEAR - S_FAR)
    return 1.0 - (S_NEAR * EYE / np.maximum(s, 0.3) - EYE) / WID


def proj_header():
    ys = list(range(Y_LO, Y_HI + 1, Y_STEP))
    py = [int(round(py_of(y / WID))) for y in ys]
    s8 = [int(round(s_of(y / WID) * 256)) for y in ys]
    z = int(round(Z_SCALE * 256))
    out = ["/* Generated by games/centuryxi/tools/art.py: do not edit. */", "#ifndef CX_PROJ_H", "#define CX_PROJ_H",
           '#include <stdint.h>',
           f"#define CX_PIC_W {PIC_W}", f"#define CX_PIC_H {PIC_H}", f"#define CX_PCX {PCX}", f"#define CX_PY0 {PY0}",
           f"#define CX_DEPTH {DEPTH}", f"#define CX_PROJ_Y_LO ({Y_LO})", f"#define CX_PROJ_Y_HI {Y_HI}",
           f"#define CX_STANDS_H {STANDS_H}",
           f"#define CX_Z_SCALE {z}",
           f"static const int16_t cx_proj_py[{len(py)}] = {{" + ",".join(map(str, py)) + "};",
           f"static const uint16_t cx_proj_s[{len(s8)}] = {{" + ",".join(map(str, s8)) + "};",
           "#endif", ""]
    return "\n".join(out)


# A summer afternoon in 1994 as the broadcast showed it: the saturated green of an NTSC
# picture, the light bands warm and yellow-green, the dark bands deep and a touch blue,
# with the bold contrast of a freshly mown cup pitch.
GRASS = [((96, 200, 64), (116, 214, 80), (84, 186, 58)),     # light band: base, fleck, shade
         ((36, 146, 64), (48, 160, 74), (28, 130, 56))]      # dark band


def _world_noise(wx, wy, cell, seed):
    """Smooth noise in world space (it pans with the pitch): a random grid every `cell`
    units, bilinearly blended. -1..1."""
    rng = np.random.default_rng(seed)
    # off the pitch toward the horizon the picture covers far more ground than it shows:
    # the noise is taken over the pitch and a margin round it only
    gx = (np.clip(wx, -600, LEN + 600) / cell).astype(np.float32) + 4.0 + 600 / cell
    gy = (np.clip(wy, -300, WID + 300) / cell).astype(np.float32) + 4.0 + 300 / cell
    nx, ny = int(gx.max()) + 3, int(gy.max()) + 3
    grid = rng.uniform(-1, 1, (ny, nx)).astype(np.float32)
    x0 = np.clip(np.floor(gx).astype(np.int32), 0, nx - 2)
    y0 = np.clip(np.floor(gy).astype(np.int32), 0, ny - 2)
    fx, fy = gx - x0, gy - y0
    fx, fy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
    a = grid[y0, x0] * (1 - fx) + grid[y0, x0 + 1] * fx
    b = grid[y0 + 1, x0] * (1 - fx) + grid[y0 + 1, x0 + 1] * fx
    return a * (1 - fy) + b * fy


def grass_pixels():
    """The pitch's rows from the far boards down: world-true mowing bands, as a 1994
    broadcast showed a summer pitch. On the bands: the sun's patches and the shade of the
    stands' edge (smooth, in world space, so they pan with the grass), the cross-cut of the
    mower (a faint second stripe), the blades' texture (short streaks in the picture, the
    camera's angle on them), and the goalmouths and centre spot worn to sandy green."""
    yy, xx = np.mgrid[0:PIC_H, 0:PIC_W].astype(np.float32)
    t = inverse_t(yy + 0.5)
    s = s_of(t)
    wx = HALF_LEN + (xx + 0.5 - PCX) / s
    wy = t * WID
    band = (np.floor(wx / 96.0).astype(np.int32) & 1)
    img = np.zeros((PIC_H, PIC_W, 3), np.float32)
    for b in (0, 1):
        img[band == b] = np.array(GRASS[b][0], np.float32)
    # the sun's patches, broad and soft, and a finer mottling over them
    light = 1.0 + 0.045 * _world_noise(wx, wy, 70.0, 7) + 0.025 * _world_noise(wx, wy, 22.0, 11)
    # the mower's cross-cut: every 64 units across the pitch a touch lighter, then darker
    cross = (np.floor(wy / 64.0).astype(np.int32) & 1) * 2 - 1
    light += 0.018 * cross
    # blades: a noise field streaked down the picture, light tips and dark roots
    rng = np.random.default_rng(787)
    blade = rng.normal(0, 1, (PIC_H + 4, PIC_W)).astype(np.float32)
    blade = (blade[:-4] + blade[1:-3] + blade[2:-2] + blade[3:-1] * 0.6) / 3.6
    blade = blade + 0.35 * np.roll(blade, 1, axis=1)
    light += 0.065 * np.clip(blade, -2, 2)
    img *= light[..., None]
    for b in (0, 1):
        _, fleck, shade = (np.array(c, np.float32) for c in GRASS[b])
        m = band == b
        img[m & (blade > 1.45)] = fleck * 1.03
        img[m & (blade < -1.55)] = shade * 0.97
    # wear: the goalmouths, the penalty spots and the centre spot, patchy
    worn = np.zeros((PIC_H, PIC_W), np.float32)
    for gx in (0.0, float(LEN)):
        dx = np.abs(wx - gx) / 70.0
        dy = np.abs(wy - WID / 2) / (POST + 40.0)
        worn = np.maximum(worn, np.clip(1.0 - np.sqrt(dx * dx + dy * dy), 0, 1))
        sx = 160.0 if gx == 0 else LEN - 160.0
        d = np.sqrt(((wx - sx) / 26.0) ** 2 + ((wy - WID / 2) / 22.0) ** 2)
        worn = np.maximum(worn, np.clip(1.0 - d, 0, 1) * 0.7)
    d = np.sqrt(((wx - HALF_LEN) / 30.0) ** 2 + ((wy - WID / 2) / 24.0) ** 2)
    worn = np.maximum(worn, np.clip(1.0 - d, 0, 1) * 0.6)
    patch = 0.55 + 0.45 * _world_noise(wx, wy, 9.0, 23)
    worn = np.clip(worn * patch * 0.42, 0, 1)
    sand = np.array((146, 168, 84), np.float32)
    img = img * (1 - worn[..., None]) + sand * worn[..., None] * light[..., None]
    # the sun is high: only a touch of haze over the far side, a touch of warmth near
    depth = 0.95 + 0.07 * np.clip(t, 0, 1)
    img *= depth[..., None]
    img[..., 0] += 6 * np.clip(t, 0, 1)
    return np.clip(img, 0, 255).astype(np.uint8), wx, wy, s


def world_lines(wx, wy, s):
    """A mask of the markings, a constant two to three pixels wide in the picture."""
    w = 1.25 / s                   # half a line in world x
    wv = 1.25 / s * (WID / DEPTH) * 0.75   # and in world y
    def box(x0, y0, x1, y1):
        h = ((np.abs(wy - y0) < wv) | (np.abs(wy - y1) < wv)) & (wx >= x0 - w) & (wx <= x1 + w)
        v = ((np.abs(wx - x0) < w) | (np.abs(wx - x1) < w)) & (wy >= y0 - wv) & (wy <= y1 + wv)
        return h | v
    m = box(0, 0, LEN, WID)
    m |= (np.abs(wx - HALF_LEN) < w) & (wy >= 0) & (wy <= WID)
    mid = WID / 2
    for left in (True, False):
        x0, x1 = (0, BOX_D) if left else (LEN - BOX_D, LEN)
        m |= box(x0, mid - BOX_W, x1, mid + BOX_W)
        x0, x1 = (0, SIX_D) if left else (LEN - SIX_D, LEN)
        m |= box(x0, mid - SIX_W, x1, mid + SIX_W)
        spot = 160 if left else LEN - 160
        m |= ((wx - spot) ** 2 / 25.0 + (wy - mid) ** 2 / 36.0) < 1.0
        # the D at the edge of the box
        cx = spot
        r = np.sqrt((wx - cx) ** 2 + (wy - mid) ** 2)
        edge = BOX_D if left else LEN - BOX_D
        side = (wx > edge) if left else (wx < edge)
        m |= (np.abs(r - 118) < 1.9 / s) & side
    r = np.sqrt((wx - HALF_LEN) ** 2 + (wy - mid) ** 2)
    m |= np.abs(r - 118) < 1.9 / s
    m |= ((wx - HALF_LEN) ** 2 + (wy - mid) ** 2) < 25.0
    for cx in (0, LEN):
        for cy in (0, WID):
            r = np.sqrt((wx - cx) ** 2 + (wy - cy) ** 2)
            m |= (np.abs(r - 18) < 1.9 / s) & (wx >= 0) & (wx <= LEN) & (wy >= 0) & (wy <= WID)
    return m


def boards(img, names, font_pixels):
    """Advertising boards along the far touchline, a row of painted panels."""
    x, i = 0, 0
    y0, y1 = PY0 - 25, PY0 - 7
    cols = [((216, 32, 40), (255, 255, 255)), ((248, 208, 40), (24, 24, 88)), ((244, 244, 248), (216, 32, 40)),
            ((24, 72, 176), (255, 255, 255)), ((248, 128, 24), (255, 255, 255)), ((16, 16, 24), (248, 208, 40))]
    while x < PIC_W:
        text = names[i % len(names)]
        bgc, fg = cols[i % len(cols)]
        w = 8 * len(text) + 28
        img[y0:y1, x:x + w] = bgc
        img[y0:y0 + 2, x:x + w] = np.minimum(np.array(bgc) + 56, 255)
        img[y1 - 2:y1, x:x + w] = (np.array(bgc) * 0.6).astype(np.uint8)
        img[y0:y1, x:x + 1] = (12, 12, 18)
        font_pixels(img, x + 14, y0 + 5, text, fg)
        x += w
        i += 1
    img[y1:y1 + 2, :] = (10, 40, 22)
    img[y0 - 2:y0, :] = (12, 12, 18)


def panel(path):
    """The stadium painting at its native pixel grid."""
    im = Image.open(path).convert('RGB')
    w, h = im.size
    return im.resize((510, 284), Image.BOX)


# The supporters' colours: shirts and flags in the stands are painted in these keys, and the
# game writes the day's two sides into whatever palette entries they became (art.py
# crowd_keys, cx_crowd_kits): the home end on the left, the away end on the right.
# shirt, flag's main colour, flag's second colour
KEY_HOME = ((255, 0, 128), (128, 0, 255), (255, 80, 200))
KEY_AWAY = ((0, 255, 128), (0, 200, 255), (160, 255, 0))


def flag_at(img, x, y, w, h, keys, pole=True):
    """A supporter's flag, its pole held below: two bands of the side's flag colours."""
    H, W = img.shape[:2]
    x0, x1, y0, y1 = max(0, x), min(W, x + w), max(0, y), min(H, y + h)
    if x1 <= x0 or y1 <= y0:
        return
    mid = y + h // 2
    img[y0:min(y1, mid), x0:x1] = keys[1]
    img[max(y0, mid):y1, x0:x1] = keys[2]
    if pole and 0 <= x < W:
        img[y0:min(H, y + h + 5), x:x + 1] = (40, 34, 30)


def far_flags(img, rng, y0, y1):
    """Flags and banners over the far terraces: the home end waves its colours on the left,
    the away end on the right, the neutral middle less."""
    x = int(rng.integers(4, 20))
    while x < PIC_W - 8:
        keys = KEY_HOME if x < PIC_W // 2 else KEY_AWAY
        middle = abs(x - PIC_W // 2) < 200
        if not middle or rng.integers(0, 3) == 0:
            y = int(rng.integers(y0, y1 - 8))
            if rng.integers(0, 6) == 0:
                flag_at(img, x, y, 20, 6, keys, pole=False)          # a banner along the rows
            else:
                flag_at(img, x, y, 7, 5, keys)
        x += int(rng.integers(14, 30))


def stands(img, path, rows=(118, 259)):
    """The far stand above the boards: the painting mirrored along the ground."""
    p = np.asarray(panel(path))
    r0, r1 = rows
    strip = p[r0:r1]
    h = strip.shape[0]
    tiles = []
    w = 0
    flip = False
    while w < PIC_W + 510:
        tiles.append(strip[:, ::-1] if flip else strip)
        w += strip.shape[1]
        flip = not flip
    band = np.concatenate(tiles, 1)
    off = (band.shape[1] - PIC_W) // 2
    band = band[:, off:off + PIC_W]
    y1 = PY0 - 27
    y0 = max(0, y1 - h)
    img[y0:y1] = band[h - (y1 - y0):]
    if y0 > 0:
        img[:y0] = band[0]
    far_flags(img, np.random.default_rng(zlib.crc32(Path(path).name.encode())), max(0, y1 - 80), y1 - 6)


def goal_lines_px(x):
    """Picture points of the goal on goal line x (0 or LEN): posts, bar, net back."""
    sign = -1 if x == 0 else 1
    top = lambda p, y: (p[0], p[1] - BAR * Z_SCALE * s_of(y / WID))
    mid = WID / 2
    nf, nn = project(x, mid - POST), project(x, mid + POST)
    bf, bn = project(x + sign * 38, mid - POST), project(x + sign * 38, mid + POST)
    return nf, nn, bf, bn, top(nf, mid - POST), top(nn, mid + POST), top(bf, mid - POST), top(bn, mid + POST)


# The goal as a 1994 broadcast showed it: round white posts with a sunlit edge, a cool
# shaded side and a crisp dark outline, a bright square mesh, and the grass inside in
# the net's shade. The parts behind the men are painted into the pitch; the near post,
# the crossbar and the near side net are the sprite drawn over them (make_goal_front).
G_INK = (24, 32, 52)
G_HI = (255, 255, 255)
G_WHITE = (232, 237, 246)
G_SHADE = (164, 178, 206)
NET_ROOF = (242, 246, 255)
NET_SIDE = (218, 226, 242)
NET_BACK = (162, 176, 206)
NET_BAR = (204, 212, 230)


def _lerp(a, b, k):
    return (a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k)


def _mesh(d, p00, p10, p01, p11, nu, nv, col_u, col_v=None):
    """A panel of net over the quad p00 p10 (u) / p01 p11: nu+1 lines one way, nv+1 the other."""
    col_v = col_v or col_u
    for i in range(nu + 1):
        k = i / nu
        d.line([_lerp(p00, p10, k), _lerp(p01, p11, k)], fill=col_u)
    for j in range(nv + 1):
        k = j / nv
        d.line([_lerp(p00, p01, k), _lerp(p10, p11, k)], fill=col_v)


def _post(d, x, y0, y1, core):
    """An upright from y0 down to y1: outline, a lit edge, white, a cool shade, outline."""
    x = int(round(x)) - core // 2
    y0, y1 = int(round(y0)), int(round(y1))
    d.line([(x - 1, y0 - 1), (x - 1, y1)], fill=G_INK)
    d.line([(x + core, y0 - 1), (x + core, y1)], fill=G_INK)
    for c in range(core):
        col = G_HI if c == 0 else (G_SHADE if c == core - 1 else G_WHITE)
        d.line([(x + c, y0), (x + c, y1)], fill=col)


def _bar(d, a, b):
    """The crossbar running into the picture: lit along its top, shaded under."""
    for off, col in ((-2, G_INK), (2, G_INK), (-1, G_HI), (1, G_SHADE), (0, G_WHITE)):
        d.line([(a[0], a[1] + off), (b[0], b[1] + off)], fill=col)


def net_into(img, x):
    """What of the goal stands behind the men, painted into the pitch."""
    nf, nn, bf, bn, tf, tn, tbf, tbn = goal_lines_px(x)
    im = Image.fromarray(img)
    # the net's shade on the grass: the goal's own footprint, solid
    m = Image.new('L', im.size, 0)
    ImageDraw.Draw(m).polygon([nf, nn, bn, bf], fill=255)
    a = np.asarray(img).astype(np.int32)
    k = np.asarray(m) > 0
    # flat there, the two bands' shade and nothing more: the textured grass, the net, its shade
    # and the sunlit grass beside it were more colours than a 16 x 16 tile holds, and the
    # tiles under the net came out a checkerboard of light and dark
    lum = (a[..., 0] * 3 + a[..., 1] * 6 + a[..., 2]) // 10
    a[k & (lum >= 128)] = np.array(GRASS[0][0], np.int32) * 3 // 4
    a[k & (lum < 128)] = np.array(GRASS[1][0], np.int32) * 3 // 4
    im = Image.fromarray(a.clip(0, 255).astype(np.uint8))
    d = ImageDraw.Draw(im)
    # back wall and far side: seen through the mouth, in the shade of the roof
    _mesh(d, bf, bn, tbf, tbn, 13, 9, NET_BACK)
    _mesh(d, nf, bf, tf, tbf, 6, 11, NET_SIDE)
    # the roof catches the sun
    _mesh(d, tf, tn, tbf, tbn, 13, 6, NET_ROOF)
    # the frame at the back: ground bars, uprights, the top bar
    for p, q in ((bf, bn), (nf, bf), (bf, tbf), (tbf, tbn), (tf, tbf)):
        d.line([p, q], fill=NET_BAR)
    _post(d, nf[0], tf[1], nf[1], 3)
    return np.asarray(im).copy()


def near_stand(img, y0, names, font_pixels):
    """The near side, as a television camera on the halfway gantry sees it: a row of ad
    boards, then the backs and heads of the front rows, bigger toward the bottom of the
    picture, some with a scarf or an arm up. Drawn from a fixed seed: the same each build."""
    rng = np.random.default_rng(1994)
    cols = [((24, 72, 176), (255, 255, 255)), ((248, 208, 40), (24, 24, 88)), ((216, 32, 40), (255, 255, 255)),
            ((244, 244, 248), (24, 72, 176)), ((16, 16, 24), (248, 208, 40)), ((248, 128, 24), (255, 255, 255))]
    by0, by1 = y0, y0 + 16
    x, i = 0, 3
    while x < PIC_W:
        text = names[i % len(names)]
        bgc, fg = cols[i % len(cols)]
        w = 8 * len(text) + 28
        img[by0:by1, x:x + w] = bgc
        img[by0:by0 + 2, x:x + w] = np.minimum(np.array(bgc) + 56, 255)
        img[by1 - 2:by1, x:x + w] = (np.array(bgc) * 0.6).astype(np.uint8)
        img[by0:by1, x:x + 1] = (12, 12, 18)
        font_pixels(img, x + 14, by0 + 3, text, fg)
        x += w
        i += 1
    # behind the boards: the dark of the terrace, then rows of supporters from behind
    img[by1:] = (28, 24, 34)
    shirts = [(216, 32, 40), (24, 72, 176), (248, 208, 40), (244, 244, 248), (32, 150, 70), (248, 128, 24),
              (120, 40, 140), (40, 40, 52), (90, 160, 220)]
    hairs = [(24, 20, 24), (60, 40, 28), (110, 72, 40), (200, 160, 80), (40, 34, 30)]
    skins = [(232, 176, 136), (196, 132, 96), (140, 92, 64), (100, 62, 44)]
    row, y = 0, by1 + 4
    H = img.shape[0]
    while y < H + 10:
        size = 7 + row * 2                       # nearer rows are bigger
        step = size + 2
        xs = np.arange(-(row % 2) * step // 2, PIC_W + step, step)
        for cx in xs:
            cx = int(cx + rng.integers(-2, 3))
            sh = shirts[int(rng.integers(0, len(shirts)))]
            keys = KEY_HOME if cx < PIC_W // 2 else KEY_AWAY
            fan = rng.integers(0, 20) < 7                 # in his side's shirt
            if fan:
                sh = keys[0]
            hr = hairs[int(rng.integers(0, len(hairs)))]
            # shoulders: a rounded block, a shade darker at the bottom
            x0, x1 = cx - size, cx + size
            sy0, sy1 = y + size // 2, y + size * 2
            if sy0 < H and sy1 > 0 and x1 > 0 and x0 < PIC_W:
                yy, xx = np.mgrid[max(0, sy0):min(H, sy1), max(0, x0):min(PIC_W, x1)]
            else:
                yy = np.zeros((0, 0))
            if yy.size:
                m = ((xx - cx) / float(size)) ** 2 + ((yy - sy0) / float(size * 1.4)) ** 2 <= 1.0
                part = img[max(0, sy0):min(H, sy1), max(0, x0):min(PIC_W, x1)]
                part[m] = sh
                if not fan:
                    part[m & (yy > sy0 + size)] = (np.array(sh) * 0.75).astype(np.uint8)
            # the back of the head
            r = max(3, size // 2)
            hy0, hy1 = y - r, y + r
            if hy0 < H and hy1 > 0 and cx + r > 0 and cx - r < PIC_W:
                yy, xx = np.mgrid[max(0, hy0):min(H, hy1), max(0, cx - r):min(PIC_W, cx + r)]
            else:
                yy = np.zeros((0, 0))
            if yy.size:
                m = (xx - cx) ** 2 + (yy - y) ** 2 <= r * r
                part = img[max(0, hy0):min(H, hy1), max(0, cx - r):min(PIC_W, cx + r)]
                part[m] = hr
                if rng.integers(0, 6) == 0:                 # a bald head or short crop: skin shows
                    part[m] = skins[int(rng.integers(0, len(skins)))]
            # a flag held up over the heads, the side's colours
            if row >= 1 and rng.integers(0, 9) == 0 and y - size * 2 - 10 > by1:
                fw, fh = 8 + size, 5 + size // 2
                flag_at(img, cx, y - r - fh - 6, fw, fh, keys)
            # now and then a scarf or an arm in the air
            elif rng.integers(0, 7) == 0 and y - size * 2 > by1:
                ax = cx + (size // 2 if rng.integers(0, 2) else -size // 2)
                img[max(by1, y - size * 2):y, max(0, ax - 1):min(PIC_W, ax + 2)] = sh
        row += 1
        y += size + 3


def make_ground(painting, font_pixels, names):
    img, wx, wy, s = grass_pixels()
    img[world_lines(wx, wy, s)] = (238, 242, 236)
    top = PY0 - 7
    img[:top] = (24, 20, 30)
    stands(img, painting)
    boards(img, names, font_pixels)
    # the near apron: a strip of rougher grass, then the near stand (boards, the crowd's backs)
    y = int(py_of(1.0)) + 16
    img[y:] = (img[y:].astype(np.int32) * 7 // 8).astype(np.uint8)
    near_stand(img, y + 6, names, font_pixels)
    img = net_into(img, 0)
    img = net_into(img, LEN)
    return img[:STANDS_H].copy(), img[STANDS_H:].copy()


def make_goal_front(x, bulge=False):
    """The near post, the crossbar and the near side net, drawn over the men; on the bulging
    frame the back wall is pushed out by the ball. RGBA, and its picture origin."""
    nf, nn, bf, bn, tf, tn, tbf, tbn = goal_lines_px(x)
    pts = (nf, nn, tf, tn, tbn, tbf, bn, bf)
    x0 = int(min(p[0] for p in pts)) - 4
    y0 = int(min(p[1] for p in pts)) - 4
    x1 = int(max(p[0] for p in pts)) + 4
    y1 = int(max(p[1] for p in pts)) + 4
    w = (x1 - x0 + 15) // 16 * 16
    h = (y1 - y0 + 15) // 16 * 16
    im = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    o = lambda p: (p[0] - x0, p[1] - y0)
    rgba = lambda c: c + (255,)
    # the near side net faces the camera: a clean square mesh the men show through
    _mesh(d, o(nn), o(bn), o(tn), o(tbn), 7, 12, rgba(NET_SIDE))
    if bulge:
        # the back wall billows toward the stand: a fan of net lines bowing out
        push = -12 if x == 0 else 12
        for k in np.linspace(0, 1, 9):
            a_ = _lerp(bf, bn, k)
            b_ = _lerp(tbf, tbn, k)
            c_ = ((a_[0] + b_[0]) / 2 + push * (1 - abs(k - 0.5) * 1.4), (a_[1] + b_[1]) / 2)
            d.line([o(a_), o(c_), o(b_)], fill=rgba(NET_ROOF))
        for k in np.linspace(0.15, 0.85, 5):
            row = [_lerp(_lerp(bf, tbf, k), _lerp(bn, tbn, k), j / 8) for j in range(9)]
            row = [(p[0] + push * (1 - abs(j / 8 - 0.5) * 1.4), p[1]) for j, p in enumerate(row)]
            d.line([o(p) for p in row], fill=rgba(NET_ROOF))
    # its frame: the bar along the top and the ground bar back to the near corner
    d.line([o(tn), o(tbn)], fill=rgba(NET_BAR))
    d.line([o(nn), o(bn)], fill=rgba(NET_BAR))
    d.line([o(bn), o(tbn)], fill=rgba(NET_BAR))
    # the crossbar, then the near post over its end
    _bar(d, o(tn), o(tf))
    _post(d, o(nn)[0], o(tn)[1] - 1, o(nn)[1], 4)
    return np.asarray(im).copy(), (x0, y0)
