def offset(im,dx,dy):
    out=Image.new("P",im.size)
    out.paste(im,(dx,dy))
    return out


def legs(parts,who,n):
    p,l,c=models.p,models.l,models.contour
    if who=="jack":
        for side,contours,lights,boots in [("far_leg",BOXER_FAR,BOXER_LIGHT_FAR,BOXER_BOOT_FAR),("near_leg",BOXER_NEAR,BOXER_LIGHT_NEAR,BOXER_BOOT_NEAR)]:
            d=parts[side];near=side=="near_leg";pts=contours[n]
            c(d,pts,3 if near else 2);p(d,lights[n],4 if near else 3)
            shoe=boots[n];c(d,shoe,9 if near else 8)
            l(d,[(shoe[0][0]+2,shoe[0][1]+2),(shoe[1][0]-2,shoe[1][1]+2)],10)
            low=max(y for x,y in shoe)
            sole=[(x,y) for x,y in shoe if y==low]
            if len(sole)>=2:l(d,sole,14)
        return
    a,b=(GINGA_FAR[n],GINGA_NEAR[n]) if who=="amara" else (KARATE[n],KARATE_NEAR[n])
    for side,data in [("far_leg",a),("near_leg",b)]:
        d=parts[side];near=side=="near_leg";shape,light,foot=data
        c(d,shape,6 if near else 5);p(d,light,7 if near else 6)
        c(d,foot,3 if near else 2)
        # Deliberate knee/cloth separation, never a detached shadow duplicate.
        if who=="kenji" and n in (0,4):
            l(d,[(97,108),(102,112),(107,110)] if near and n==0 else
                 [(57,115),(62,112),(67,114)] if not near and n==0 else
                 [(63,116),(68,112),(72,114)] if near else [(94,114),(99,117),(103,115)],5)


