    args.output.mkdir(parents=True,exist_ok=False);busts={}
    for who in ('kenji','jack','amara'):
        data,colors=portrait(who);busts[who]=(data,colors)
        save(args.output/(who+'-bust.png'),data,colors)
        save(args.output/(who+'-portrait.png'),data[16:112,8:88],colors)
        card,pal=title(busts,who);save(args.output/(who+'-card.png'),card,pal)
    data,colors=title(busts);save(args.output/'title.png',data,colors)
    top,bottom,pal=hud();save(args.output/'hud-top.png',top,pal);save(args.output/'hud-bottom.png',bottom,pal)
    number,pal=digits();save(args.output/'digits.png',number,pal)
