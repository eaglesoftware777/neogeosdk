    for n,(x,y,r,b) in enumerate(structures):
        d.rectangle((x,y,r,b),fill=2 if n%2 else 3)
        d.line([(x,y),(r,y),(r,b)],fill=4)
        for yy in range(y+8,b-4,12):
            for xx in range(x+4,r-2,8):d.rectangle((xx,yy,xx+1,yy+3),fill=5 if (yy//12+n)%3 else 6)
    d.line([(0,190),(176,155),(351,190)],fill=4,width=2)
    d.line([(0,200),(176,169),(351,200)],fill=3)
    canvas=np.asarray(image).copy();lookup={c:i for i,c in enumerate(colors)}
    positions=[('jack',0,3),('kenji',128,-3),('amara',256,1)] if focus is None else [(focus,128,30)]
    for who,x,y in positions:
        data,pal=busts[who];mapping=[]
        for rgb in pal:
            rgb=tuple(int(i) for i in rgb)
            if rgb not in lookup:lookup[rgb]=len(colors);colors.append(rgb)
            mapping.append(lookup[rgb])
        for yy in range(160):
            target=y+yy
            if not 0<=target<224:continue
            row=data[yy];mask=row>0
            canvas[target,x:x+96][mask]=np.asarray(mapping,np.uint8)[row[mask]]
    return canvas,np.asarray(colors,np.uint8)

