@dataclass
class Part:
    image: Image.Image
    contact: tuple | None = None
    hurt: tuple | None = None

    def shifted(self, x=0, y=0):
        out=Image.new('P', (160,160));out.paste(self.image,(x,y))
        box=None if self.contact is None else (self.contact[0]+x,self.contact[1]+y,*self.contact[2:])
        hurt=None if self.hurt is None else (self.hurt[0]+x,self.hurt[1]+y,*self.hurt[2:])
        return Part(out,box,hurt)

class Ink:
    def __init__(self):
        self.image=Image.new('P',(160,160));self.d=ImageDraw.Draw(self.image)
        self.contact=None;self.hurt=None
    def shape(self, points, color):
        self.d.polygon(points,fill=color)
        self.d.line(points+[points[0]],fill=1,width=1)
    def patch(self, points, color):self.d.polygon(points,fill=color)
    def line(self, points, color, width=1):self.d.line(points,fill=color,width=width)
    def dot(self,x,y,color):self.d.point((x,y),fill=color)
    def box(self,x,y,w,h):self.contact=(x,y,w,h)
    def part(self):return Part(self.image,self.contact,self.hurt)

