def compose(parts):
    flat=np.zeros((160,160),np.uint8)
    for name in ORDER:
        data=np.asarray(parts[name].image)
        flat[data>0]=data[data>0]
    return flat

def palette(who):
    colors=np.array([list(bytes.fromhex(c)) for c in COLORS[who]],np.uint8)
    out=np.zeros((256,3),np.uint8);out[:len(colors)]=colors
    return out

def preview(parts,who):
    indices=compose(parts);rgb=np.full((160,160,3),(24,32,48),np.uint8)
    mask=indices>0;rgb[mask]=palette(who)[indices[mask]]
    return Image.fromarray(rgb)
