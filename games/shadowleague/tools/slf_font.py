LIT_ROWS = 3   # rows 0..2 take the lit ink, the rest the shaded ink


def tile(rows):
    g = np.zeros((8, 8), np.uint8)
    mask = np.zeros((8, 8), bool)
    for r, line in enumerate(rows.split('|')):
        for c, ch in enumerate(line):
            if ch == '#':
                mask[r, c] = True
    shadow = np.zeros_like(mask)
    shadow[1:, 1:] = mask[:-1, :-1]
    g[shadow & ~mask] = 2
    ys = np.arange(8)[:, None].repeat(8, 1)
    g[mask] = np.where(ys[mask] < LIT_ROWS, 1, 3)
    return g


def glyph_tiles():
    out = {}
    for ch, rows in G.items():
        out[ord(ch)] = tile(rows)
        if ch.isalpha():
            out[ord(ch.lower())] = out[ord(ch)]
    out[32] = np.zeros((8, 8), np.uint8)
    return out


def preview(path, text="SHADOW LEAGUE FIGHTING 0123456789 !?-/:().'+=", scale=4):
    from PIL import Image
    tiles = glyph_tiles()
    pal = np.array([(20, 20, 32), (250, 250, 250), (16, 16, 24), (170, 180, 200)], np.uint8)
    img = np.zeros((8, 8 * len(text)), np.uint8)
    for i, ch in enumerate(text):
        img[:, i * 8:i * 8 + 8] = tiles.get(ord(ch), tiles[32])
    Image.fromarray(pal[img]).resize((img.shape[1] * scale, 8 * scale), Image.NEAREST).save(path)
