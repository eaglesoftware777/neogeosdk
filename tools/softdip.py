#!/usr/bin/env python3
"""Builds a game's soft DIP table (the operator's settings on an arcade board).

The system ROM's settings menu reads a table the cartridge header points at
(0x116 Japan, 0x11A USA, 0x11E Europe). Its layout:

    16 bytes   the game's name in the menu
     2 words   two time settings, minutes and seconds in BCD (0xFFFF: unused)
     2 bytes   two count settings, 1..99 (0xFF: unused)
    10 bytes   ten option settings: high nibble the default choice, low nibble
               how many choices (0: unused)
    then 12-character strings: each time setting's name, each count setting's
    name, then each option's name followed by its choices

The game reads what the operator chose with ng_dip_time / ng_dip_count /
ng_dip_option (sdk/ng_system.h); a console has no settings menu and always
reads the defaults.

The spec is a text file, one line each:

    name: CENTURY XI
    time: ROUND TIME | 1:30          (at most two)
    count: LIVES | 3                 (at most two)
    option: CPU LEVEL | LEVEL 1, LEVEL 2, *LEVEL 3, LEVEL 4
                                     (at most ten, 2..15 choices, * the default)

Lines starting with # are comments. Names and choices are cut or padded to 12
characters (16 for the game's name), upper case. One table serves all three
regions and must fit the header's 384-byte data area.

    python3 tools/softdip.py games/<game>/softdip.txt games/<game>/softdip_table.h
"""
import sys
from pathlib import Path

AREA = 384


def field(text, width):
    t = text.strip().upper()
    if len(t) > width:
        raise SystemExit(f'softdip: "{t}" is longer than {width} characters')
    return list(t.ljust(width).encode('ascii'))


def bcd(v):
    return ((v // 10) << 4) | (v % 10)


def build(spec_text):
    name, times, counts, options = 'GAME', [], [], []
    for n, raw in enumerate(spec_text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith('#'):
            continue
        key, _, rest = line.partition(':')
        key = key.strip().lower()
        if key == 'name':
            name = rest.strip()
            continue
        label, _, value = rest.partition('|')
        if key == 'time':
            m, _, s = value.strip().partition(':')
            times.append((label, int(m), int(s or 0)))
        elif key == 'count':
            counts.append((label, int(value)))
        elif key == 'option':
            choices = [c.strip() for c in value.split(',') if c.strip()]
            default = [i for i, c in enumerate(choices) if c.startswith('*')]
            choices = [c.lstrip('*').strip() for c in choices]
            if not 2 <= len(choices) <= 15:
                raise SystemExit(f'softdip: line {n}: an option has 2 to 15 choices')
            options.append((label, choices, default[0] if default else 0))
        else:
            raise SystemExit(f'softdip: line {n}: unknown "{key}"')
    if len(times) > 2 or len(counts) > 2 or len(options) > 10:
        raise SystemExit('softdip: at most two times, two counts and ten options')
    out = field(name, 16)
    for i in range(2):
        if i < len(times):
            _, m, s = times[i]
            out += [bcd(m), bcd(s)]
        else:
            out += [0xFF, 0xFF]
    for i in range(2):
        out.append(counts[i][1] if i < len(counts) else 0xFF)
    for i in range(10):
        if i < len(options):
            _, choices, default = options[i]
            out.append((default << 4) | len(choices))
        else:
            out.append(0)
    for label, *_ in times:
        out += field(label, 12)
    for label, _ in counts:
        out += field(label, 12)
    for label, choices, _ in options:
        out += field(label, 12)
        for c in choices:
            out += field(c, 12)
    if len(out) > AREA:
        raise SystemExit(f'softdip: the table is {len(out)} bytes; the header area holds {AREA}')
    return out, options


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    spec, dest = Path(sys.argv[1]), Path(sys.argv[2])
    table, options = build(spec.read_text())
    rows = [', '.join(f'0x{b:02X}' for b in table[i:i + 16]) for i in range(0, len(table), 16)]
    lines = [f'/* Generated by tools/softdip.py from {spec.name}: edit that, not this.',
             ' * The operator\'s settings: one table for all three regions (the header points',
             ' * at it three times). The game reads them with ng_dip_option(n):']
    for i, (label, choices, default) in enumerate(options):
        lines.append(f' *   option {i}: {label.strip().upper()} ({", ".join(choices)}; default {choices[default]})')
    lines.append(' */')
    lines += [f'#define NG_SOFTDIP_BYTES {len(table)}',
              'const uint8_t ng_softdip_table[] __attribute__ ((section ("neogeo_gamedata"), used, aligned (2))) = {']
    lines += [f'    {r},' for r in rows]
    lines += ['};', '']
    dest.write_text('\n'.join(lines))
    print(f'softdip: {len(table)} bytes, {len(options)} options -> {dest}')


if __name__ == '__main__':
    main()
